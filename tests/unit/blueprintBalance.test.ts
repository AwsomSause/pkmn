// Balance simulations for the four Blueprint systems. They run the real data and flow code many times and check the
// numbers stay inside the design's bounds (Blueprint: no exploit that trivializes the main progression).
// Set BALANCE_REPORT=1 to write the numbers to docs/plans/balance-report.md.

import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { generateRoute } from '../../src/core/expedition/graph';
import { levelCap } from '../../src/core/regions';
import { beginMinigame, minigameAct, minigameTick, minigameView } from '../../src/core/minigame/flow';
import { hashSeed, Rng } from '../../src/core/rng';
import { chooseStarter, createRun } from '../../src/core/run';
import type { RunState } from '../../src/core/state';
import { content } from './helpers';

const gym = content.balance.money.gymLeaderPerLevel;
const report: string[] = ['# Blueprint balance report', '', 'Generated by `BALANCE_REPORT=1 npx vitest run tests/unit/blueprintBalance.test.ts`. Prize money is compared with a gym leader at the same level (80 per level).', ''];

function stopRun(seed: string, gameId: string, region = 0): RunState {
  const run = structuredClone(chooseStarter(content, createRun(content, { runId: 'bal', seed, archetypeId: 'red' }), 0));
  run.regionIndex = region;
  const node = run.stage!.map.nodes.find((n) => n.column === 1)!;
  node.sides = [{ id: 'mg', kind: 'minigame', minigameId: gameId, used: false }];
  run.stage!.current = node.id;
  return run;
}

/** A player who takes the first enabled choice at random: the floor of skill. */
function botPlay(run: RunState, seed: string): RunState {
  const r = new Rng(hashSeed(seed));
  for (let step = 0; step < 800 && !run.minigame!.outcome; step++) {
    const open = minigameView(content, run).cells.filter((c) => !c.disabled);
    if (open.length > 0) run = minigameAct(content, run, r.pick(open).id);
    if (!run.minigame!.outcome && step % 3 === 2) run = minigameTick(content, run);
  }
  return run;
}

describe('boss and expedition prize money', () => {
  it('rises with tier and stays between half and three and a half gym prizes', () => {
    const rows: { name: string; tier: number; ratio: number }[] = [
      ...content.raids.raids.map((x) => ({ name: `raid ${x.id}`, tier: x.tier, ratio: x.rewards.moneyPerLevel / gym })),
      ...content.totems.totems.map((x) => ({ name: `totem ${x.id}`, tier: ['early', 'mid', 'late', 'grand'].indexOf(x.tier) + 1, ratio: x.rewards.moneyPerLevel / gym })),
      ...content.expeditions.expeditions.map((x) => ({ name: `expedition ${x.id}`, tier: x.tier, ratio: x.rewards.moneyPerLevel / gym })),
    ];
    report.push('## Prize money per level, as a share of a gym leader', '', '| Source | Tier | Ratio |', '|---|---|---|', ...rows.map((r) => `| ${r.name} | ${r.tier} | ${r.ratio.toFixed(2)} |`), '');
    for (const r of rows) {
      expect(r.ratio, r.name).toBeGreaterThanOrEqual(0.5);
      expect(r.ratio, r.name).toBeLessThanOrEqual(3.5);
    }
    const raids = content.raids.raids.filter((r) => !r.legendary).sort((a, b) => a.tier - b.tier);
    for (let i = 1; i < raids.length; i++) expect(raids[i]!.rewards.moneyPerLevel).toBeGreaterThanOrEqual(raids[i - 1]!.rewards.moneyPerLevel);
  });
});

describe('expedition routes', () => {
  it('have a sensible mix of fights and recovery across 300 seeds each', () => {
    report.push('## Expedition routes (300 seeds each)', '', '| Expedition | Stops | Fights | Rests | Resource stops |', '|---|---|---|---|---|');
    for (const def of content.expeditions.expeditions) {
      let stops = 0, fights = 0, rests = 0, other = 0;
      for (let i = 0; i < 300; i++) {
        const nodes = generateRoute(def, new Rng(hashSeed(`bal-${def.id}-${i}`)));
        stops += nodes.length;
        fights += nodes.filter((n) => ['wild', 'trainer', 'elite', 'totem', 'raid', 'finale'].includes(n.kind)).length;
        rests += nodes.filter((n) => n.kind === 'rest').length;
        other += nodes.filter((n) => ['cache', 'research', 'megaEnergy', 'mystery', 'recruit'].includes(n.kind)).length;
      }
      const avg = (n: number) => n / 300;
      report.push(`| ${def.id} | ${avg(stops).toFixed(1)} | ${avg(fights).toFixed(1)} | ${avg(rests).toFixed(1)} | ${avg(other).toFixed(1)} |`);
      expect(avg(fights) / avg(stops)).toBeGreaterThan(0.3);
      expect(avg(fights) / avg(stops)).toBeLessThan(0.85);
      expect(avg(rests)).toBeLessThan(avg(stops) / 2);
    }
    report.push('');
  });
});

describe('minigame payouts', () => {
  it('a random player earns little, a perfect player is held to the stage cap', () => {
    const eco = content.minigames.economy;
    report.push('## Minigames', '', `Stage money cap: ${eco.stageMoneyCap} × region number. Gym prize at the region's level cap shown for scale.`, '', '| Region | Cap | Gym prize | Cap / gym |', '|---|---|---|---|');
    for (let region = 0; region < 4; region++) {
      const cap = eco.stageMoneyCap * (region + 1);
      const prize = gym * levelCap(content, region);
      report.push(`| ${region + 1} | ${cap} | ${prize} | ${(cap / prize).toFixed(2)} |`);
      expect(cap / prize, `region ${region + 1}`).toBeLessThanOrEqual(0.5);
    }
    report.push('', '| Game | Tier | Random-player gold/silver/bronze/none (of 30) | Mean money | Best-medal money |', '|---|---|---|---|---|');
    for (const def of content.minigames.games) {
      for (let tier = 0; tier < 3; tier++) {
        const medals = { gold: 0, silver: 0, bronze: 0, none: 0 };
        let money = 0;
        for (let i = 0; i < 30; i++) {
          const run = botPlay(beginMinigame(content, stopRun(`bal-${def.id}-${i}`, def.id), 'mg', tier), `bot-${i}`);
          medals[run.minigame!.outcome!.medal] += 1;
          money += run.minigame!.outcome!.money;
        }
        const best = Math.round(def.rewardTable.gold.money * eco.tierMultipliers[tier]!);
        report.push(`| ${def.id} | ${tier + 1} | ${medals.gold}/${medals.silver}/${medals.bronze}/${medals.none} | ${(money / 30).toFixed(0)} | ${best} |`);
        // A random player must not be handed gold on most runs: games need skill.
        expect(medals.gold, `${def.id} tier ${tier + 1}`).toBeLessThanOrEqual(15);
        expect(money / 30, `${def.id} tier ${tier + 1}`).toBeLessThanOrEqual(best);
      }
    }
    report.push('');
  }, 120000);

  it('writes the report when asked', () => {
    if (process.env.BALANCE_REPORT) writeFileSync('docs/plans/balance-report.md', `${report.join('\n')}\n`);
    expect(report.length).toBeGreaterThan(0);
  });
});
