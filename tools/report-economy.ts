// Whole-run balance simulations (Untitled doc Phase G): the test autoplayer plays the same seeds at every difficulty,
// with and without Death-Block, and the report shows how far it gets and what it earns.
//
//   npm run report:economy            print the report
//   npm run report:economy -- --write also write docs/quality/ECONOMY_REPORT.md
//
// Read-only: it never changes the game data. Read the trend, not the exact numbers: the bot is simple.

import { mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type * as Auto from '../tests/unit/autoplay.ts';
import type * as Rules from '../src/core/rules.ts';
import { closeModules, loadModule, root } from './lib/gameModules.ts';

const { autoplay } = await loadModule<typeof Auto>('/tests/unit/autoplay.ts');
const { RUN_RULES, rewardMultiplier } = await loadModule<typeof Rules>('/src/core/rules.ts');
await closeModules();

const SEEDS = ['eco-a', 'eco-b', 'eco-c', 'eco-d', 'eco-e', 'eco-f'];
const started = Date.now();
const rows: string[] = [];
for (const d of RUN_RULES.difficulties) {
  for (const deathBlock of [false, true]) {
    const rules = { modeId: 'standard', difficultyId: d.id, modifierIds: [], deathBlock };
    const runs = SEEDS.map((seed) => autoplay({ seed, steps: 4000, rules, healOnMap: true }));
    const mean = (f: (r: (typeof runs)[number]) => number) => (runs.reduce((n, r) => n + f(r), 0) / runs.length).toFixed(1);
    const early = Math.round((runs.filter((r) => r.phase === 'over' && r.encountersCompleted < 10).length / runs.length) * 100);
    rows.push(`| ${d.name} | ${deathBlock ? 'on' : 'off'} | x${rewardMultiplier(rules)} | ${mean((r) => r.encountersCompleted)} | ${mean((r) => r.badges.length)} | ${mean((r) => r.log.counters.moneyEarned ?? 0)} | ${early}% |`);
  }
}
const md = [
  '# Economy and difficulty simulation',
  '',
  `Generated by \`npm run report:economy\`. ${SEEDS.length} seeds per row, the test autoplayer (always picks the first damaging move, heals on the map). Same seeds, same numbers.`,
  '',
  'The bot is crude (no item use beyond Poké Balls, no switching tactics), so it loses early at every setting above Story. Read the direction of the numbers: harder presets must lose sooner, and Death-Block rows match their "off" rows when the bot loses again right after the saved wipe.',
  '',
  '| Difficulty | Death-Block | Reward x | Avg encounters | Avg badges | Avg money earned | Lost before encounter 10 |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...rows,
  '',
  `(${Math.round((Date.now() - started) / 1000)} s)`,
  '',
].join('\n');
console.log(md);
if (process.argv.includes('--write')) {
  const dir = join(root, 'docs', 'quality');
  mkdirSync(dir, { recursive: true });
  const path = join(dir, 'ECONOMY_REPORT.md');
  writeFileSync(path, md);
  console.log(`Wrote ${relative(root, path)}`);
}
