// Rival simulation report (Rivalry Engine phase 13): the test autoplayer plays many seeds and the report counts
// how many rivals each run makes, how their rivalries end, repeats, ranks, Ultimate Rivals, and any contradictions.
//
//   npm run report:rivals                  print the report (40 seeds; exits 1 if any contradiction)
//   npm run report:rivals -- --seeds 100   more seeds
//   npm run report:rivals -- --write       also write docs/quality/RIVAL_REPORT.md
//
// Read-only: it never changes the game data. The bot is simple, so read the trend, not the exact numbers.

import { mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type * as Auto from '../tests/unit/autoplay.ts';
import type * as Sim from '../src/core/rivals/simReport.ts';
import { closeModules, loadModule, root } from './lib/gameModules.ts';

const { autoplay } = await loadModule<typeof Auto>('/tests/unit/autoplay.ts');
const { rivalRunStats } = await loadModule<typeof Sim>('/src/core/rivals/simReport.ts');
await closeModules();

const arg = (name: string) => process.argv.indexOf(name);
const count = arg('--seeds') >= 0 ? Number(process.argv[arg('--seeds') + 1]) : 40;
const started = Date.now();
const stats = Array.from({ length: count }, (_, i) => {
  const run = autoplay({ seed: `rival-sim-${i}`, steps: 20000, healOnMap: true, smart: true, starterLevel: 40, rules: { modeId: "standard", difficultyId: "story", modifierIds: [], deathBlock: true } });
  return { seed: `rival-sim-${i}`, cleared: run.encountersCompleted, ...rivalRunStats(run) };
});

const sum = (f: (s: (typeof stats)[number]) => number) => stats.reduce((n, s) => n + f(s), 0);
const mean = (f: (s: (typeof stats)[number]) => number) => (sum(f) / Math.max(1, stats.length)).toFixed(2);
const pct = (f: (s: (typeof stats)[number]) => boolean) => `${Math.round((stats.filter(f).length / Math.max(1, stats.length)) * 100)}%`;
const merge = (pick: (s: (typeof stats)[number]) => Record<string, number>) => {
  const out: Record<string, number> = {};
  for (const s of stats) for (const [k, v] of Object.entries(pick(s))) out[k] = (out[k] ?? 0) + v;
  return Object.entries(out).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', ') || 'none';
};
const contradictions = stats.flatMap((s) => s.contradictions.map((c) => `${s.seed}: ${c}`));

const lines = [
  '# Rival simulation report',
  '',
  `Generated by \`npm run report:rivals\` over ${stats.length} autoplayed seeds (smart bot, Story difficulty, Death-Block on, level 40 starter, up to 20000 steps each, so runs last long enough for rivals to return). Read the trend, not the exact numbers.`,
  '',
  '| Measure | Value |',
  '|---|---|',
  `| Encounters cleared per run (mean) | ${mean((s) => s.cleared)} |`,
  `| Rivals per run (mean) | ${mean((s) => s.rivals)} |`,
  `| Runs with no rival | ${pct((s) => s.rivals === 0)} |`,
  `| Rival rematches per run (mean) | ${mean((s) => s.encounters)} |`,
  `| Ladder states (all rivals) | ${merge((s) => s.states)} |`,
  `| Arc resolutions | good ${sum((s) => s.resolutions.good)}, bad ${sum((s) => s.resolutions.bad)}, open ${sum((s) => s.resolutions.open)} |`,
  `| Ranks won without you | ${merge((s) => s.ranks)} |`,
  `| Runs with an Ultimate Rival | ${pct((s) => s.ultimate)} |`,
  `| Runs that settled the Ultimate quest | ${pct((s) => s.ultimateSettled)} |`,
  `| Repeated rivals (same class and name) | ${sum((s) => s.repeats)} |`,
  `| Contradictions | ${contradictions.length} |`,
  '',
  ...(contradictions.length > 0 ? ['## Contradictions', '', ...contradictions.map((c) => `- ${c}`), ''] : []),
];
console.log(lines.join('\n'));
console.log(`(${((Date.now() - started) / 1000).toFixed(1)} s)`);
if (process.argv.includes('--write')) {
  const out = join(root, 'docs/quality/RIVAL_REPORT.md');
  mkdirSync(join(root, 'docs/quality'), { recursive: true });
  writeFileSync(out, `${lines.join('\n')}\n`);
  console.log(`wrote ${relative(root, out)}`);
}
if (contradictions.length > 0) process.exitCode = 1;
