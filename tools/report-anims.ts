// The per-move animation report (Visual Bible §4.4): for every move, its
// animation family, which file it plays first, its stand-by, and its status.
//
//   npm run report:anims            print the summary
//   npm run report:anims -- --write also write docs/quality/MOVE_ANIMATIONS.md
//
// Status: "supported" = the move's own animation (pack or PokeRogue);
// "limited" = it borrows another move's animation (Z-Moves and Max Moves:
// none of the packs has attack animations for them), with its family effect
// as the last stand-by.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type * as Data from '../src/data/index.ts';
import type * as Presentation from '../src/data/presentation.ts';
import type * as Families from '../src/core/presentation/families.ts';
import type * as MoveAnims from '../src/core/presentation/moveAnims.ts';
import { closeModules, loadModule, root } from './lib/gameModules.ts';

const { getContent } = await loadModule<typeof Data>('/src/data/index.ts');
const { moveAnims } = await loadModule<typeof Presentation>('/src/data/presentation.ts');
const { moveFamily, FAMILY_IDS, FAMILY_RECIPES } = await loadModule<typeof Families>('/src/core/presentation/families.ts');
const { presentationFor, animChoice } = await loadModule<typeof MoveAnims>('/src/core/presentation/moveAnims.ts');
await closeModules();

const content = getContent();
const data = moveAnims();
const moves = [...content.moves.values()].sort((a, b) => a.id.localeCompare(b.id));
const families = new Map<string, number>();
const sources = { pack: 0, own: 0, type: 0 };
const rows: string[] = [];
for (const m of moves) {
  const look = presentationFor(data, m.id);
  const family = moveFamily(m, look);
  families.set(family, (families.get(family) ?? 0) + 1);
  const choice = animChoice(look);
  const kind = look.pack ? 'pack' : look.source;
  sources[kind]++;
  const first = look.pack ? `Essentials \`${look.pack}\`` : look.source === 'own' ? `PokeRogue \`${look.anim}\`` : `borrowed \`${look.anim}\``;
  const standBy = [choice.alt ? `PokeRogue \`${choice.alt}\`` : null, `family`].filter(Boolean).join(' → ');
  rows.push(`| ${m.name} | ${FAMILY_RECIPES[family].label} | ${first} | ${standBy} | ${look.source === 'type' ? 'limited' : 'supported'} |`);
}

const summary = [
  `Moves: ${moves.length}. Essentials pack animation first: ${sources.pack}. PokeRogue's own: ${sources.own}. Borrowed (limited): ${sources.type}.`,
  `Families in use: ${[...families.keys()].length} of ${FAMILY_IDS.length}.`,
];
console.log(summary.join('\n'));

if (process.argv.includes('--write')) {
  const md = `# Move animations

Generated by \`npm run report:anims -- --write\`. Presentation only: the battle rules never read any of this.

${summary.join('\n')}

Each move tries, in order: the director's Essentials pack animation (\`ess-*\`, imported by \`npm run data:pack-anims\`), PokeRogue's animation, then its family effect (\`src/ui/battleFx/familyFx.ts\`) in its type colour. Reduced or off motion skips all three.

## Known limits

- **Max/G-Max Moves and 10,000,000 Volt Thunderbolt** borrow a same-type animation: none of the packs has attack animations for them. They add the signature family burst on top. The other Z-Moves play the Pokémon Memories repo's Essentials animations (same format, imported with \`npm run data:pack-anims -- … --missing-only\`), and every transformation has its own cinematic (\`src/ui/battleFx/cinematics.ts\`).
- **EBDX's 442 scripted move animations** are Ruby code, not frame data, so they are not played; their graphics are reused for effects.
- Essentials' per-sprite colour overlay isn't carried over (darkening tones are).

## Families

| Family | Moves |
|---|---|
${FAMILY_IDS.map((f) => `| ${FAMILY_RECIPES[f].label} | ${families.get(f) ?? 0} |`).join('\n')}

## Every move

| Move | Family | First choice | Stand-by | Status |
|---|---|---|---|---|
${rows.join('\n')}
`;
  writeFileSync(join(root, 'docs', 'quality', 'MOVE_ANIMATIONS.md'), md);
  console.log('Wrote docs/quality/MOVE_ANIMATIONS.md');
}
