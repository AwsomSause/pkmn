// Accessibility audit checklist for releases (W12 F223): `node tools/a11y-checklist.ts` writes
// docs/quality/a11y-checklist.md. The settings part is built from the settings list, so it cannot drift; the manual
// checks are tick boxes for the person doing the release.
import { writeFileSync } from 'node:fs';
import type * as Registry from '../src/core/settingsRegistry.ts';
import { closeModules, loadModule } from './lib/gameModules.ts';

const { SETTINGS } = await loadModule<typeof Registry>('/src/core/settingsRegistry.ts');
await closeModules();

const a11y = SETTINGS.filter((s) => s.category === 'accessibility' || s.also?.includes('accessibility'));
const lines = [
  '# Accessibility audit checklist',
  '',
  'Run this before each release. Generated by `node tools/a11y-checklist.ts`; do not edit by hand.',
  '',
  '## Settings that must work (from the settings list)',
  '',
  ...a11y.map((s) => `- [ ] **${s.label}** (${s.applies}): ${s.description}`),
  '',
  '## Manual checks',
  '',
  '- [ ] Whole game can be played with the keyboard only (menus, battles, map, shops, events).',
  '- [ ] Whole game can be played with a gamepad using the default map.',
  '- [ ] Touch controls work on a phone-sized window and nothing is clipped.',
  '- [ ] High Contrast, Dyslexia font and the largest Font size: text stays readable and nothing overlaps.',
  '- [ ] Reduced Motion profile: no shake, flash or large movement anywhere (battles, evolutions, transitions).',
  '- [ ] Reduced Flash: no full-screen flashes more than three times a second.',
  '- [ ] Colour is never the only signal (type markers on; HP bars also show numbers).',
  '- [ ] Sound off: every message that matters is also shown as text.',
  '- [ ] Every button has a visible focus mark and a tooltip or label.',
  '- [ ] Browser zoom 200% and window 800x450: no screen is unusable.',
  '- [ ] No console errors on the title, Hub, map, battle and settings screens.',
  '',
];
writeFileSync(new URL('../docs/quality/a11y-checklist.md', import.meta.url).pathname, lines.join('\n'));
console.log(`wrote docs/quality/a11y-checklist.md (${a11y.length} settings)`);
