// Asset audit (catalog #133, #134): every file imported from a pack (public/assets/images/packs and the egg jingle)
// must have a row in docs/quality/asset-provenance.md; also lists oversized and unused files.
//
//   npm run report:assets            print the report, exit 1 when a pack file has no provenance row
//   npm run report:assets -- --write also write docs/quality/ASSET_AUDIT.md
//
// Read-only: it never changes assets.

import { execSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const assets = join(root, 'public/assets');
const OVERSIZED = 500 * 1024;

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
}

/** Expands `{a,b}` groups (also empty alternatives) and turns `<name>` into a wildcard. */
function expand(pattern: string): string[] {
  const m = pattern.match(/\{([^{}]*)\}/);
  if (!m) return [pattern];
  return m[1]!.split(',').flatMap((alt) => expand(pattern.replace(m[0], alt)));
}

const prov = readFileSync(join(root, 'docs/quality/asset-provenance.md'), 'utf8');
const covered = new Set<string>();
for (const line of prov.split('\n')) {
  const cell = line.match(/^\| `([^`]+)` \|/);
  if (!cell) continue;
  for (const p of expand(cell[1]!)) covered.add(p);
}

const packFiles = [...walk(join(assets, 'images/packs')), ...walk(join(assets, 'audio/se')).filter((f) => f.endsWith('egg_get.ogg'))].map((f) => relative(assets, f).replaceAll('\\', '/'));
const missing = packFiles.filter((f) => !covered.has(f));
const everything = walk(assets).filter((f) => !f.endsWith('manifest.json'));
const oversized = everything.filter((f) => statSync(f).size > OVERSIZED).map((f) => ({ f: relative(assets, f).replaceAll('\\', '/'), kb: Math.round(statSync(f).size / 1024) })).sort((a, b) => b.kb - a.kb);
const totalMb = (everything.reduce((n, f) => n + statSync(f).size, 0) / 1048576).toFixed(1);
const unused = packFiles.filter((f) => {
  const base = f.split('/').pop()!.replace(/\.[^.]+$/, '');
  try {
    execSync(`grep -rqF -- ${JSON.stringify(base)} src`, { cwd: root });
    return false;
  } catch {
    return true;
  }
});

const lines = [
  '# Asset audit',
  '',
  `Generated by \`npm run report:assets\`. ${everything.length} files, ${totalMb} MB under \`public/assets\`.`,
  '',
  `- Pack files without a provenance row: **${missing.length}**${missing.length ? '\n' + missing.map((f) => `  - \`${f}\``).join('\n') : ''}`,
  `- Pack files whose name appears nowhere in \`src\` (maybe unused): **${unused.length}**${unused.length ? '\n' + unused.map((f) => `  - \`${f}\``).join('\n') : ''}`,
  `- Files over ${OVERSIZED / 1024} KB: **${oversized.length}** (largest: ${oversized.slice(0, 5).map((o) => `${o.f} ${o.kb} KB`).join(', ') || 'none'})`,
  '',
];
console.log(missing.length || process.argv.includes('--write') ? lines.join('\n') : `ok   Asset provenance [pack-files-without-provenance]: 0 (${packFiles.length} pack files, ${unused.length} maybe unused, ${oversized.length} over ${OVERSIZED / 1024} KB)`);
if (process.argv.includes('--write')) {
  mkdirSync(join(root, 'docs/quality'), { recursive: true });
  writeFileSync(join(root, 'docs/quality/ASSET_AUDIT.md'), lines.join('\n') + '\n');
}
if (missing.length) process.exit(1);
